// Para utilizar o for é necessario ter um contador para que delimitemos a quantidade de vezes que algo sera repetido. A estrutura do for recebe inicialização, condição e incremento.

console.log("Vou Contar até 10 depois dizer morango");


//  Inicialização   Condição   Incremento
for (let i = 0;     i <= 10;       i+=2  ) {
    console.log(i);
}

console.log("Morango!!!");