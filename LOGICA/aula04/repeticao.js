// Declarar uma variavel chamada contador que recebe um valor numérico
let contador = 0

// enquanto contador for menor do que 10 repita
while (contador <= 10) {
    console.log ("Olha a hora do café")
    console.log ("Vem tomar seu café!")
    console.log ("Café da manha, café da tarde! não importa!")
    console.log ("Venha tomar seu café!")

    // Adicionar ++ após o nome de uma variavel faz com seja adicionado 1 ao seu valor 
    contador++ 
    console.log(contador);
}